import fs from 'fs'
import path from 'path'

const bookRoot = path.join(process.cwd(), 'docs/md/books')
const manifestPath = path.join(
  process.cwd(),
  'docs/.vitepress/theme/data/pdf-manifest.js'
)

if (!fs.existsSync(bookRoot)) {
  console.warn('Books directory not found:', bookRoot)
  process.exit(0)
}

const dirs = fs.readdirSync(bookRoot).filter(name => {
  const full = path.join(bookRoot, name)
  return fs.statSync(full).isDirectory()
})

const normalizeName = (name) => name.replace(/[-_]+/g, ' ')

const listFiles = (dir, extension) => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const fullPath = path.join(dir, entry.name)
  if (entry.isDirectory()) return listFiles(fullPath, extension)
  return entry.name.toLowerCase().endsWith(extension) ? [fullPath] : []
})

const pdfPaths = listFiles(bookRoot, '.pdf')

if (pdfPaths.length > 0) {
  const manifest = pdfPaths.map(pdfPath => {
    const relativePath = path.relative(bookRoot, pdfPath).split(path.sep).join('/')
    const [category] = relativePath.split('/')
    const fileName = path.basename(pdfPath, path.extname(pdfPath))
    return {
      name: normalizeName(fileName),
      category,
      repoPath: `docs/md/books/${relativePath}`
    }
  }).sort((a, b) => a.repoPath.localeCompare(b.repoPath, 'zh-Hans-CN'))

  fs.mkdirSync(path.dirname(manifestPath), { recursive: true })
  fs.writeFileSync(
    manifestPath,
    `// Generated by scripts/generate-pdf-pages.js.\nexport default ${JSON.stringify(manifest, null, 2)}\n`,
    'utf8'
  )
}

for (const dir of dirs) {
  const fullDir = path.join(bookRoot, dir)
  const pdfFiles = fs.readdirSync(fullDir).filter(f => f.toLowerCase().endsWith('.pdf'))

  // 1) Ensure there is an index.md that renders a PDF list for this folder
  //    If index.md already exists, keep it so users can add custom text.
  const indexMdPath = path.join(fullDir, 'index.md')
  if (!fs.existsSync(indexMdPath)) {
    const title = normalizeName(dir)
    const indexContent = `---
title: ${title}
---

# ${title}

> 📖 在此处写一些本书的简介（例如用途、章节概览、阅读建议等）。
>
> 你也可以添加封面图，例如：
>
> \`\`\`md
> ![封面](./cover.png)
> \`\`\`
>
<PdfList dir="${dir}" />
`
    fs.writeFileSync(indexMdPath, indexContent, 'utf8')
  }

  // 2) Create individual markdown pages for each PDF so it can be linked directly.
  //    If the markdown file already exists, do not overwrite it so it can be customized.
  pdfFiles.forEach(file => {
    const base = file.replace(/\.pdf$/i, '')
    const mdPath = path.join(fullDir, `${base}.md`)

    const existingMds = fs.readdirSync(fullDir).filter(f =>
      f.endsWith('.md') && !f.startsWith('index')
    )
    const repoPath = `docs/md/books/${dir}/${file}`
    const alreadyReferenced = existingMds.some(f => {
      const content = fs.readFileSync(path.join(fullDir, f), 'utf8')
      return content.includes(`./${file}`) || content.includes(`repo-path="${repoPath}"`)
    })
    if (alreadyReferenced) return

    const title = normalizeName(base)
    const mdContent = `---
title: ${JSON.stringify(title)}
---

# ${title}

<PdfViewer repo-path="${repoPath}" />
`

    // Existing pages may contain custom metadata and prose; migrate them below.
    if (!fs.existsSync(mdPath)) {
      fs.writeFileSync(mdPath, mdContent, 'utf8')
    }
  })
}

if (pdfPaths.length > 0) {
  for (const mdPath of listFiles(bookRoot, '.md')) {
    const existing = fs.readFileSync(mdPath, 'utf8')
    if (!existing.includes('const pdfUrl = new URL(')) continue

    const match = existing.match(
      /new URL\(\s*(['"])(\.\/[^'"]+\.pdf)\1,\s*import\.meta\.url\s*\)\.href/
    )
    if (!match) continue

    const pdfPath = path.resolve(path.dirname(mdPath), match[2])
    const relativePath = path.relative(process.cwd(), pdfPath).split(path.sep).join('/')
    let updated = existing
      .replace(/<script setup>\s*(?:import PdfViewer[^\n]*\n)?const pdfUrl = new URL\([\s\S]*?\)\.href\s*<\/script>\s*/m, '')
      .replace(
        /<PdfViewer :src="pdfUrl"(?: repo-path="[^"]+")? \/>/,
        `<PdfViewer repo-path="${relativePath}" />`
      )
    if (!updated.startsWith('---\n')) {
      const heading = updated.match(/^# (.+)$/m)?.[1] || path.basename(mdPath, '.md')
      updated = `---\ntitle: ${JSON.stringify(heading)}\n---\n\n${updated}`
    }
    fs.writeFileSync(mdPath, updated, 'utf8')
  }
}

console.log(`Generated PDF pages for ${dirs.length} book folder(s) and indexed ${pdfPaths.length} PDF(s)`)
